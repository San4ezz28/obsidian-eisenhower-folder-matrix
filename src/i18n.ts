export function getLocale(setting: LanguageSetting = "auto"): "ru" | "en" {
  if (setting === "ru" || setting === "en") return setting;
  // Official Obsidian API (available since Obsidian 1.8.7).
  const fromObsidian = typeof getLanguage === "function" ? getLanguage() : "en";
  return (typeof fromObsidian === "string" ? fromObsidian : "en").toLowerCase().split(/[-_]/)[0] === "ru" ? "ru" : "en";
}
export function t(key: TranslationKey, setting: LanguageSetting = "auto", params: Record<string, string | number> = {}): string {
  const template = (getLocale(setting) === "ru" ? RU : EN)[key] || EN[key];
  return template.replace(/\{(\w+)\}/g, (whole, k: string) => params[k] === undefined ? whole : String(params[k]));
}
